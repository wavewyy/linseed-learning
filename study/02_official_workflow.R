.libPaths(c("D:/single cell项目/Linseed/library", .libPaths()))
setwd("D:/single cell项目/Linseed")
library(linseed)
set.seed(20261014)
lo <- LinseedObject$new("GSE19830", samples=10:42, topGenes=10000)
lo$calculatePairwiseLinearity()
lo$calculateSpearmanCorrelation()
lo$calculateSignificanceLevel(100)
print(lo$significancePlot(0.01))
lo$filterDatasetByPval(0.01)
print(lo$svdPlot())
lo$setCellTypeNumber(3)
lo$project("full")
print(lo$projectionPlot(color="filtered"))
lo$project("filtered")
lo$smartSearchCorners(dataset="filtered", error="norm")
lo$deconvolveByEndpoints()
print(plotProportions(lo$proportions))
lo$selectGenes(100)
print(lo$tsnePlot())
data("proportionsLiverBrainLung")
print(dotPlotPropotions(lo$proportions, proportionsLiverBrainLung[,10:42], guess=TRUE))
dir.create("results/full", recursive=TRUE, showWarnings=FALSE)
write.csv(lo$proportions, "results/full/proportions.csv")
saveRDS(lo, "results/full/linseed_object.rds")
writeLines(capture.output(sessionInfo()), "results/full/sessionInfo.txt")

